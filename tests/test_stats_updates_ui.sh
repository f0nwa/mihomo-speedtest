#!/bin/sh
set -eu
ROOT=$(CDPATH= cd -- "$(dirname "$0")/.." && pwd)
FILE="$ROOT/web/stats_app_updates.js"
CSS="$ROOT/web/stats_style.css"
fail() { echo "FAIL: $*" >&2; exit 1; }

# Задача веб-редизайна раздела "Обновления" (см. CHANGELOG):
# 1. кнопка "Обновить" - в той же карточке/строке, что и "Проверить сейчас".
grep -q "row.appendChild(checkBtn); if (available) { row.appendChild(updateBtn); }" "$FILE" \
  || fail "п.1: кнопки 'Проверить сейчас'/'Обновить' не в одной строке сверху"
grep -q "card('Обновления')" "$FILE" || fail "п.1: нет единой карточки 'Обновления' сверху"
grep -q "Настройки обновлений" "$FILE" || fail "нет карточки 'Настройки обновлений' на вкладке «Обновления»"
grep -q "save_updates" "$FILE" || fail "карточка настроек обновлений должна сохранять через action=save_updates"
SETTINGS_FILE=$(dirname "$FILE")/stats_app_settings.js
if grep -q "fields: \['update_channel'" "$SETTINGS_FILE"; then
  fail "настройки обновлений должны быть убраны из раздела «Настройки»"
fi

# 2. нет отдельного экрана подтверждения - клик "Обновить" сразу запускает
#    prepare, а после его завершения (без подтверждения) сам запускает apply.
! grep -q "buildUpdatesConfirmScreen" "$FILE" || fail "п.2: экран подтверждения не должен использоваться в обычном пути"
grep -q "function handlePrepareDone" "$FILE" || fail "п.2: нет автоматического продолжения prepare->apply"
grep -q "startApply(job.plan_id, 0, 0, container);" "$FILE" \
  || fail "п.2: обычный путь (план не требует подтверждения) не продолжается сам"

# ...но подстраховка (локальные изменения/миграция конфига) - консольное
# сообщение + кнопка принудительного повтора, а не автоматическая перезапись.
grep -q "'Обновить принудительно'" "$FILE" || fail "нет кнопки принудительного повтора при блокирующем подтверждении"

# 3. мини консоль - живой лог этапов/ошибок поверх опроса /api/updates/status.
grep -q "function renderConsoleLog" "$FILE" || fail "п.3: нет построчного рендера мини консоли"
grep -q "'update-console'" "$FILE" || fail "п.3: мини консоль не использует класс update-console"
grep -q "renderConsoleLog(consolePre, data.log)" "$FILE" || fail "п.3: мини консоль не подключена к data.log"
grep -q "update-console" "$CSS" || fail "п.3: в CSS нет стиля мини консоли"

# 4. полный список файлов больше не выводится - вместо него текст релиза.
! grep -q "buildFilesTable" "$FILE" || fail "п.4: buildFilesTable больше не должен использоваться"
grep -q "lc.notes" "$FILE" || fail "п.4: раздел не показывает notes (текст релиза)"
grep -q "card(available ? 'Что нового' : 'Что нового в установленной версии')" "$FILE" || fail "п.4: нет карточки 'Что нового'"

# 5. бейдж - синий, мигает (CSS), доступность обновления учитывает 'missing'.
count=$(grep -c "f.state === 'missing'" "$FILE")
[ "$count" = 2 ] || fail "5: ожидалось 2 проверки f.state === 'missing' (badge + доступность кнопки), найдено $count"
grep -q "nav-badge-blink" "$CSS" || fail "5: нет анимации мигания бейджа"
grep -q "background:var(--accent)" "$CSS" || fail "5: бейдж должен быть синим (var(--accent)), не красным"
! grep -q "^\.nav-badge{.*#dc2626" "$CSS" || fail "5: в .nav-badge остался красный цвет"


# 6. текст над кнопками - одна короткая фраза по available:
#    "Доступна новая версия: N" либо "Установлена актуальная версия: N"
#    (прежнее "Доступная версия релиза: N. Уже установлено, обновление не
#    требуется." владелец счёл избыточным).
grep -q "available ? 'Доступна новая версия: ' : 'Установлена актуальная версия: '" "$FILE" \
  || fail "6: текст сводки не различает 'доступна новая' и 'установлена актуальная' по available"
! grep -q "Уже установлено, обновление не требуется" "$FILE" \
  || fail "6: осталась избыточная фраза 'Уже установлено, обновление не требуется'"
! grep -q "Доступная версия релиза" "$FILE" \
  || fail "6: осталась фраза 'Доступная версия релиза'"

# 7. кнопка "Обновить" появляется только когда есть обновление (available) -
#    ни неактивной при актуальной версии, ни после неудачной проверки.
! grep -q "updateBtn.disabled = !available" "$FILE" \
  || fail "7: кнопка 'Обновить' не должна показываться неактивной - только скрываться"

# После применения обновления страница сама перезагружается (иначе в
# браузере остаётся старый app.js и непонятно, встало ли обновление),
# на время перезапуска веб-службы показывается понятный статус, а после
# перезагрузки раздел показывает итог последнего применения.
grep -q "location.reload()" "$FILE" || fail "после применения обновления страница не перезагружается"
grep -q "fetchJson('/api/updates/check', { method: 'POST' }).then(reload, reload)" "$FILE" || fail "перезагрузка должна идти после перепроверки версии"
grep -q "Нет ответа от веб-службы - при обновлении она перезапускается" "$FILE" || fail "нет статуса на время перезапуска веб-службы"
grep -q "function startUpdateJobPolling(onUpdate, onError)" "$FILE" || fail "ошибки опроса статуса обновления молча глотаются"
grep -q "'Последнее обновление применено'" "$FILE" || fail "раздел не показывает итог последнего применения"
grep -q "'Последнее обновление не применено'" "$FILE" || fail "раздел не показывает ошибку последнего применения"

if command -v node >/dev/null 2>&1; then
  node --input-type=module --check < "$FILE"
fi

echo "test_stats_updates_ui.sh: OK"
