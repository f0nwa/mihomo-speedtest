#!/bin/sh
set -eu
ROOT=$(CDPATH= cd -- "$(dirname "$0")/.." && pwd)
JS="$ROOT/web/stats_app_updates.js"
fail() { echo "FAIL: $*" >&2; exit 1; }

# Пункт 3 фидбека: после успешного "Обновить" бейдж на вкладке Обновления
# продолжал мигать, пока пользователь не жал "Проверить сейчас" вручную -
# refreshUpdatesBadge() сам по себе просто пересчитывает наличие обновления
# по СТАРОМУ last_check.plan (сохранённому до применения обновления), а не
# запускает новую проверку. Нужно, чтобы после apply сама страница дёргала
# /api/updates/check (как это делает кнопка "Проверить сейчас"), и только
# затем обновляла бейдж/KPI-плитку. С 2026-09-28 после перепроверки
# страница перезагружается целиком (новый app.js), бейдж пересчитывается
# уже на свежей странице.

line=$(grep -n "'Обновление применено\. Страница" "$JS" | head -1 | cut -d: -f1)
[ -n "$line" ] || fail "js: не нашёл строку 'Обновление применено. Страница...'"
window=$(sed -n "${line},$((line + 15))p" "$JS")
echo "$window" | grep -q "/api/updates/check" \
  || fail "js: после 'Обновление применено.' не вызывается повторная проверка /api/updates/check"
echo "$window" | grep -q "location.reload()" \
  || fail "js: после применения обновления страница не перезагружается"

echo OK
